#!/usr/bin/env node
/**
 * The declarative runtime's reference mapping (issue #82): the css-variables
 * exporter's output on plugin-kit's `canonical` fixture, written as a mapping
 * table instead of code. Generated, never hand-edited: every row comes from
 * css-variables' own coverage, in the order its stylesheet writes them, so the
 * table can't be tuned to pass.
 *
 * `scripts/check-plugins.mjs` runs the mapping through the runtime and
 * requires `variables.transtyle.css` byte-identical to css-variables' and the
 * coverage rows (`variable`, `slot`, `class`) equal. When css-variables or the
 * fixture changes, that check fails and this script regenerates the table.
 *
 * Run: node scripts/gen-reference-mapping.mjs   (also: npm run gen:reference-mapping)
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fixtureIR } from '@transtyle/plugin-kit';
import { formatColor, formatHslTriplet, formatHex, contrastRatio, mix, makeUnits } from '@transtyle/core';
import cssVariables from '../packages/exporter-css-variables/src/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const REFERENCE_MAPPING = join(root, 'packages/core/test-fixtures/declarative/reference.mapping.json');
const PROJECT = 'conformance-fixture';
export const DARK_SELECTOR = '[data-color-scheme="dark"]';

/** The context plugin-kit gives an exporter, with a project name the header can show. */
export function referenceCtx(config) {
  return {
    config,
    targetConfig: { output: 'dist', options: {} },
    units: makeUnits(config),
    formatColor, formatHslTriplet, formatHex, contrastRatio, mix,
    projectName: PROJECT,
    siblings: [],
    targetVersion: null,
    targetProfile: null,
  };
}

const PARTS = { '-size': 'fontSize', '-weight': 'fontWeight', '-leading': 'lineHeight', '-family': 'fontFamily' };

export async function buildReferenceMapping() {
  const ir = await fixtureIR('canonical');
  const { files, coverage } = cssVariables.emit(ir, referenceCtx({ name: PROJECT }));
  const css = files.find((f) => f.path === 'variables.transtyle.css').contents;
  const bySlot = new Map(coverage.map((c) => [c.variable, c]));
  const lines = css.split('\n');
  const open = lines.indexOf(':root {');
  const header = lines.slice(0, open - 1).map((l) => l.replaceAll(PROJECT, '{projectName}'));
  const rows = [];
  for (const line of lines.slice(open + 1, lines.indexOf('}', open))) {
    const variable = /^ {2}(--[\w-]+):/.exec(line)[1];
    const row = bySlot.get(variable);
    const entry = ir.modes[ir.defaultMode].get(row.slot);
    const out = { variable, slot: row.slot };
    if (entry.type === 'typography') out.part = PARTS[Object.keys(PARTS).find((s) => variable.endsWith(s))];
    rows.push(out);
  }
  return {
    $schema: 'https://transtyle.dev/schemas/mapping/v0.json',
    name: 'css-variables-reference',
    description: "exporter-css-variables' output on plugin-kit's canonical fixture, as a table. Generated by scripts/gen-reference-mapping.mjs.",
    files: [
      {
        path: 'variables.transtyle.css',
        template: 'css-custom-properties',
        header,
        blocks: [{ mode: { 'color-scheme': 'dark' }, selector: DARK_SELECTOR }],
        comments: 'provenance',
        rows,
      },
    ],
  };
}

export const render = (mapping) => JSON.stringify(mapping, null, 2) + '\n';

if (import.meta.url === `file://${process.argv[1]}`) {
  const mapping = await buildReferenceMapping();
  writeFileSync(REFERENCE_MAPPING, render(mapping));
  console.log(`✔ wrote packages/core/test-fixtures/declarative/reference.mapping.json (${mapping.files[0].rows.length} rows)`);
}
