#!/usr/bin/env node
/**
 * Mechanical converter: compiled transtyle artifacts → browser-loadable demo CSS,
 * written into each example's demo/themes/. See docs/specs/demo-app.md
 * ("Theme comes only from compiled output").
 *
 * Two transforms, no value editing:
 *  1. dist/daisyui/daisyui.transtyle.css — the exporter emits `@plugin "daisyui/theme"`
 *     blocks (Tailwind-build input, not browser CSS). Each block becomes a
 *     `[data-theme="<name>"]` ruleset consumable by the daisyUI CDN stylesheet.
 *     → demo/themes/daisyui.css
 *  2. dist/shadcn/globals.transtyle.css — font & radius scale live inside the
 *     `@theme inline` block, which browsers drop as an unknown at-rule. Those
 *     lines are re-emitted under `:root` (the `--color-*` mappings are Tailwind
 *     utility wiring and stay out; demo CSS reads `var(--primary)` etc. directly).
 *     → demo/themes/extras.css
 *
 * Run after `transtyle build` in any example:  node examples/build-demo-themes.mjs
 * Outputs are committed.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const examplesDir = dirname(fileURLToPath(import.meta.url));

// daisyUI theme structure vars the exporter does not emit (colors/radius only);
// values are daisyUI 5's own defaults, required for components to render.
const DAISY_STRUCTURAL_DEFAULTS = [
  "  /* daisyUI structural defaults — not design-token-derived, not emitted by the exporter */",
  "  --size-selector: 0.25rem;",
  "  --size-field: 0.25rem;",
  "  --border: 1px;",
  "  --depth: 1;",
  "  --noise: 0;",
].join("\n");

function convertDaisy(src, sourcePath) {
  const blocks = [...src.matchAll(/@plugin\s+"daisyui\/theme"\s*\{([\s\S]*?)\n\}/g)];
  if (blocks.length === 0) return null;
  const out = [];
  for (const [, body] of blocks) {
    const name = body.match(/name:\s*"([^"]+)"/)?.[1];
    if (!name) continue;
    const kept = body
      .split("\n")
      .filter((l) => /^\s*(--|color-scheme:)/.test(l))
      .join("\n");
    out.push(`[data-theme="${name}"] {\n${kept}\n${DAISY_STRUCTURAL_DEFAULTS}\n}`);
  }
  return (
    `/* GENERATED by examples/build-demo-themes.mjs — do not edit.\n` +
    ` * Mechanical conversion of ${sourcePath} (@plugin blocks → [data-theme] rulesets\n` +
    ` * for use with the daisyUI CDN stylesheet). Values untouched. */\n\n` +
    out.join("\n\n") + "\n"
  );
}

function extractShadcnExtras(src, sourcePath) {
  const theme = src.match(/@theme inline\s*\{([\s\S]*?)\n\}/)?.[1];
  if (!theme) return null;
  const kept = theme
    .split("\n")
    .filter((l) => /^\s*--(font|radius)-/.test(l))
    .join("\n");
  if (!kept) return null;
  return (
    `/* GENERATED by examples/build-demo-themes.mjs — do not edit.\n` +
    ` * Font & radius lines extracted from ${sourcePath}'s \`@theme inline\` block,\n` +
    ` * which browsers discard as an unknown at-rule. Values untouched. */\n\n` +
    `:root {\n${kept}\n}\n`
  );
}

let wrote = 0;
for (const ds of readdirSync(examplesDir, { withFileTypes: true })) {
  if (!ds.isDirectory()) continue;
  const demoDir = join(examplesDir, ds.name, "demo");
  if (!existsSync(demoDir)) continue;
  const outDir = join(demoDir, "themes");
  mkdirSync(outDir, { recursive: true });

  const daisyPath = join(examplesDir, ds.name, "dist/daisyui/daisyui.transtyle.css");
  if (existsSync(daisyPath)) {
    const css = convertDaisy(readFileSync(daisyPath, "utf8"), `examples/${ds.name}/dist/daisyui/daisyui.transtyle.css`);
    if (css) {
      writeFileSync(join(outDir, "daisyui.css"), css);
      console.log(`examples/${ds.name}/demo/themes/daisyui.css`);
      wrote++;
    }
  }
  const shadcnPath = join(examplesDir, ds.name, "dist/shadcn/globals.transtyle.css");
  if (existsSync(shadcnPath)) {
    const css = extractShadcnExtras(readFileSync(shadcnPath, "utf8"), `examples/${ds.name}/dist/shadcn/globals.transtyle.css`);
    if (css) {
      writeFileSync(join(outDir, "extras.css"), css);
      console.log(`examples/${ds.name}/demo/themes/extras.css`);
      wrote++;
    }
  }
}
if (!wrote) {
  console.error("No compiled outputs found — run `transtyle build` in the example dirs first.");
  process.exit(1);
}
